/* The Worker knows items only by their Bengali names, but the public website
   has an English page. The goods list in src/lib/catalog.ts carries both, so
   this writes the pairs out as a plain lookup the Worker can import
   (server/src/catalog-en.js). An item he typed himself, or renamed, is not in
   the list and simply shows under its Bengali name in English too.

   The output is committed. Run `npm run schema` after the catalogue changes. */

import { build } from 'vite'
import { mkdtempSync, writeFileSync } from 'fs'
import { tmpdir } from 'os'
import { join, dirname } from 'path'
import { pathToFileURL, fileURLToPath } from 'url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = mkdtempSync(join(tmpdir(), 'sitekhata-catalog-'))

await build({
  configFile: false, logLevel: 'error', root: ROOT,
  build: {
    outDir: out, emptyOutDir: true, minify: false, target: 'es2022', sourcemap: false,
    lib: { entry: { catalog: 'src/lib/catalog.ts' }, formats: ['es'] },
  },
})
const { CATALOG, CATS } = await import(pathToFileURL(join(out, 'catalog.js')).href)

/* English names for the section headings the catalogue groups goods under. */
const CAT_EN = {
  'পাইপ': 'Pipes', 'ফিটিংস': 'Fittings', 'ভালভ ও কল': 'Valves and taps', 'বাথরুম': 'Bathroom',
  'বিদ্যুৎ': 'Electrical', 'নির্মাণ সামগ্রী': 'Building material', 'হার্ডওয়্যার': 'Hardware', 'রং': 'Paint',
}
const missing = CATS.filter((c) => !CAT_EN[c])
if (missing.length) throw new Error('no English heading for: ' + missing.join(', '))

const ITEMS = {}
for (const c of CATALOG) ITEMS[c.name_bn] = { en: c.name_en, cat: c.cat }

writeFileSync(join(ROOT, 'server/src/catalog-en.js'),
  '// Generated by scripts/gen-catalog-en.mjs from src/lib/catalog.ts — do not edit by hand.\n' +
  '// The order of CATS is the order the website lists the sections in.\n' +
  'export const CATS = ' + JSON.stringify(CATS) + '\n\n' +
  'export const CAT_EN = ' + JSON.stringify(CAT_EN, null, 2) + '\n\n' +
  'export const ITEM_EN = ' + JSON.stringify(ITEMS, null, 1) + '\n')
console.log('wrote server/src/catalog-en.js —', Object.keys(ITEMS).length, 'goods in', CATS.length, 'sections')
